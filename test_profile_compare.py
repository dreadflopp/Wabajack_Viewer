    def test_multiple_profiles_require_explicit_choice(self):
        path = self.package(profiles=("One", "Two"))
        with self.assertRaisesRegex(c.ComparisonError, "Choose an authored profile"):
            c.read_package(path)
        self.assertEqual(c.read_package(path, "tWo")["profile"], "Two")

    def test_json_manifest_alias_and_bom(self):
        self.assertEqual(c.read_package(self.package(manifest_name="modlist.json"))["name"], "Example")

    def test_duplicates_and_unsafe_package_paths_are_rejected(self):
        for destination in ("../escape", "mods/Alpha/../outside", "C:/escape", "/escape", "mods/Alpha/content.txt"):
            with self.subTest(destination=destination), self.assertRaises(c.ComparisonError):
                c.read_package(self.package(extra=[{"To": destination}]))
        for text in ("+Alpha\n+ALPHA\n", "+../escape\n", "+folder/name\n"):
            with self.assertRaises(c.ComparisonError):
                c.mod_entries(text)

    def test_qt_metadata_duplicates_quotes_case_and_percent(self):
        value = c.metadata('\ufeff[general]\nVersion="1%0"\nversion="2.0"\nMODID=123\ngameName=SkyrimSE\n[installedFiles]\nsize=4\n')
        self.assertEqual(value["version"], "2.0")
        self.assertEqual(value["mod_id"], "123")
        self.assertEqual(c.metadata('[installedFiles]\n1\\fileid=456\n2\\fileid=456\n')["file_id"], "456")
        self.assertEqual(c.metadata('[installedFiles]\n1\\fileid=456\n2\\fileid=789\n')["file_id"], "")

    def test_adding_mod_does_not_report_all_mods_reordered(self):
        a, b = self.inventories(entries=[("Alpha", True)])
        self.assertFalse(self.row(c.compare_inventories(a, b))["order_differs"])

    def test_report_is_escaped_and_keeps_full_details(self):
        a, b = self.inventories()
        a["name"] = '<script>alert("name")</script>'
        report = c.compare_inventories(a, b)
        output = self.root / "report.html"
        c.write_report(report, output)
        self.assertNotIn("<script>", output.read_text())
        self.assertIn("&lt;script&gt;", output.read_text())
        output = output.with_suffix(".json")
        c.write_report(report, output)
        self.assertEqual(json.loads(output.read_text()), report)

    def test_no_profile_writes_during_comparison(self):
        before = {str(p.relative_to(self.profile)): p.read_bytes() for p in self.profile.rglob("*") if p.is_file()}
        c.compare_paths(self.package(), self.profile)
        after = {str(p.relative_to(self.profile)): p.read_bytes() for p in self.profile.rglob("*") if p.is_file()}
        self.assertEqual(before, after)

    @unittest.skipUnless(ctypes.util.find_library("xxhash"), "libxxhash not installed")
    def test_file_verification_detects_edits_with_same_metadata_and_extra_missing_files(self):
        hasher = c.FileHasher()
        digest = hasher.digest(self.mods / "Alpha/content.txt")
        a, b = self.inventories(entries=[("Alpha", True)], file_hash=digest)
        self.assertEqual(self.row(c.compare_inventories(a, b, True))["content"]["status"], "Files match")
        (self.mods / "Alpha/content.txt").write_text("edited content")
        row = self.row(c.compare_inventories(a, b, True))
        self.assertEqual(row["status"], "Metadata matches")
        self.assertEqual(row["content"]["status"], "Files differ")
        self.assertEqual(row["content"]["differences"][0]["status"], "Content differs")
        (self.mods / "Alpha/content.txt").unlink()
        (self.mods / "Alpha/extra.txt").write_text("extra")
        diffs = self.row(c.compare_inventories(a, b, True))["content"]["differences"]
        self.assertEqual({d["status"] for d in diffs}, {"Missing file", "Local file only"})

    @unittest.skipUnless(ctypes.util.find_library("xxhash"), "libxxhash not installed")
    def test_remapped_files_are_unverified_and_symlinks_rejected(self):
        a, b = self.inventories(entries=[("Alpha", True)])
        a["mods"]["alpha"]["files"]["content.txt"]["type"] = "RemappedInlineFile"
        row = self.row(c.compare_inventories(a, b, True))
        self.assertEqual(row["content"]["status"], "Files unverified")
        (self.mods / "Alpha/link").symlink_to(self.mods / "Personal", target_is_directory=True)
        with self.assertRaisesRegex(c.ComparisonError, "symlinked"):
            c.compare_inventories(a, b, True)

    def test_nondeterministic_and_unknown_outputs_are_not_hash_failures(self):
        a, b = self.inventories(entries=[("Alpha", True)])
        for kind in ("CreateBSA", "CreateBSA, Wabbajack.Lib", "TransformedTexture", "RemappedInlineFile", "ArchiveMeta", "FutureDirective"):
            with self.subTest(kind=kind):
                a["mods"]["alpha"]["files"]["content.txt"]["type"] = kind
                with patch.object(c, "FileHasher") as hasher:
                    report = c.compare_inventories(a, b, True)
                    content = self.row(report)["content"]
                    self.assertEqual(content["status"], "Files unverified")
                    self.assertEqual(content["checked"], 0)
                    self.assertEqual(content["unverifiable"], 1)
                    self.assertTrue(content["differences"][0]["reason"])
                    self.assertEqual(report["content_summary"], {"Files unverified": 1, "Not checked": 1})
                    hasher.return_value.digest.assert_not_called()

    def test_legacy_directive_aliases_are_normalized_in_package_inventory(self):
        a = c.read_package(self.package(extra=[{"$type": "TransformedTexture, Wabbajack.Lib", "To": "mods/Alpha/texture.dds", "Hash": "h", "Size": 4}]))
        self.assertEqual(a["mods"]["alpha"]["files"]["texture.dds"]["type"], "TransformedTexture")

    @unittest.skipUnless(ctypes.util.find_library("xxhash"), "libxxhash not installed")
    def test_xxhash_known_vectors_and_changes_during_read(self):
        empty = self.root / "empty"
        empty.write_bytes(b"")
        self.assertEqual(c.FileHasher().digest(empty), base64.b64encode(0xef46db3751d8e999.to_bytes(8, "little")).decode())
        with patch.object(c, "stat_signature", side_effect=[1, 2]), self.assertRaisesRegex(c.ComparisonError, "changed"):
            c.FileHasher().digest(empty)


